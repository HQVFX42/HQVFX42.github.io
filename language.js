    const entries = [];
    const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT, {
        acceptNode(node) {
            if (node.parentElement.closest('script, style, nav[aria-label="Language"]')) return NodeFilter.FILTER_REJECT;
            return Object.hasOwn(portfolioEnglish, normalize(node.textContent))
                ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
        }
    });
    while (walker.nextNode()) {
        const node = walker.currentNode;
        entries.push({ node, original: node.textContent, english: portfolioEnglish[normalize(node.textContent)] });
    }

    const search = document.getElementById('project-search');
    const originalPlaceholder = search?.placeholder;
    const nameAlias = document.querySelector('h1 span');
    function setLanguage(language) {
        document.documentElement.lang = language;
        entries.forEach(({ node, original, english }) => {
            node.textContent = language === 'en' ? english : original;
        });
        if (search) search.placeholder = language === 'en' ? 'Search projects...' : originalPlaceholder;
        if (nameAlias) nameAlias.hidden = language === 'en';
        document.querySelectorAll('[data-language]').forEach(link => {
            const selected = link.dataset.language === language;
            if (selected) link.setAttribute('aria-current', 'true');
            else link.removeAttribute('aria-current');
            link.style.color = selected ? 'var(--accent)' : '';
        });
        try { localStorage.setItem('portfolio-language', language); } catch {}
    }

    const requested = new URLSearchParams(location.search).get('lang');
    let stored;
    try { stored = localStorage.getItem('portfolio-language'); } catch {}
    setLanguage(requested === 'en' || requested === 'ko' ? requested : stored === 'en' ? 'en' : 'ko');
